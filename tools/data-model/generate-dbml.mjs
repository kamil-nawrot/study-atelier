import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LOCAL_DATABASE = 'postgresql://postgres:postgres@127.0.0.1:54322/postgres';
const OUTPUT = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../../docs/data-model/current.dbml'
);
const TABLE_NOTES = JSON.parse(
	readFileSync(new URL('./table-notes.json', import.meta.url), 'utf8')
);
const HEADER = `// Generated by tools/data-model/generate-dbml.mjs from the schema the migrations build.
// Do not edit by hand; see README.md.
`;
const USAGE = `Usage: pnpm data-model [--check] [--url <postgres url>]
  Reads the schema from a database the migrations were applied to (default: the local Supabase)
  and writes docs/data-model/current.dbml. --check compares instead of writing.`;

const CATALOG_QUERY = `
select json_build_object(
  'tables', coalesce((
    select json_agg(t) from (
      select c.relname as name, c.relrowsecurity as rls,
        (select json_agg(json_build_object(
            'name', a.attname, 'type', format_type(a.atttypid, a.atttypmod), 'notNull', a.attnotnull,
            'default', pg_get_expr(d.adbin, d.adrelid), 'identity', a.attidentity, 'generated', a.attgenerated)
            order by a.attnum)
          from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
          where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped) as columns,
        (select json_agg(json_build_object(
            'name', ic.relname, 'unique', i.indisunique, 'primary', i.indisprimary,
            'constraint', exists(select 1 from pg_constraint k where k.conindid = i.indexrelid and k.contype in ('p', 'u')),
            'where', pg_get_expr(i.indpred, i.indrelid),
            'keys', (select json_agg(json_build_object(
                'column', case when i.indkey[n - 1] = 0 then null else (select attname from pg_attribute where attrelid = c.oid and attnum = i.indkey[n - 1]) end,
                'expression', case when i.indkey[n - 1] = 0 then pg_get_indexdef(i.indexrelid, n, true) end,
                'descending', (i.indoption[n - 1] & 1) = 1) order by n)
              from generate_series(1, i.indnkeyatts) n))
            )
          from pg_index i join pg_class ic on ic.oid = i.indexrelid where i.indrelid = c.oid) as indexes,
        (select json_agg(pg_get_constraintdef(k.oid) order by k.conname)
          from pg_constraint k where k.conrelid = c.oid and k.contype = 'c') as checks
      from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
    ) t), '[]'::json),
  'refs', coalesce((
    select json_agg(r) from (
      select k.conname as name, c.relname as "table", case when rn.nspname = 'public' then rc.relname else rn.nspname || '.' || rc.relname end as target,
        (select json_agg(a.attname order by u.ord) from unnest(k.conkey) with ordinality u(attnum, ord)
          join pg_attribute a on a.attrelid = k.conrelid and a.attnum = u.attnum) as columns,
        (select json_agg(a.attname order by u.ord) from unnest(k.confkey) with ordinality u(attnum, ord)
          join pg_attribute a on a.attrelid = k.confrelid and a.attnum = u.attnum) as "targetColumns",
        k.confdeltype as "onDelete", k.confupdtype as "onUpdate",
        (select json_agg(a.attname order by u.ord) from unnest(k.confdelsetcols) with ordinality u(attnum, ord)
          join pg_attribute a on a.attrelid = k.conrelid and a.attnum = u.attnum) as "deleteColumns"
      from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_class rc on rc.oid = k.confrelid
        join pg_namespace rn on rn.oid = rc.relnamespace
      where k.contype = 'f' and c.relnamespace = 'public'::regnamespace
    ) r), '[]'::json)
)`;

const ACTIONS = { c: 'cascade', n: 'set null', d: 'set default', r: 'restrict' };

export function quoteText(text) {
	return `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

export function typeName(type) {
	return /^[a-z_0-9]+$/.test(type) ? type : `"${type}"`;
}

export function listedValues(check) {
	const match =
		/^CHECK \(\(?(?:\(?(\w+)\)?(?:::\w+)?) = ANY \(\(?ARRAY\[(.*?)\]\)?(?:::\w+\[\])?\)\)\)?$/.exec(
			check
		);
	if (!match) return null;
	const values = [...match[2].matchAll(/'((?:[^']|'')*)'/g)].map((entry) =>
		entry[1].replaceAll("''", "'")
	);
	return values.length > 0 ? { column: match[1], values } : null;
}

function columnLine(column, primaryKey, notes) {
	const settings = [];
	if (primaryKey) settings.push('pk');
	if (column.notNull && !primaryKey) settings.push('not null');
	if (column.identity) settings.push('increment');
	const hasDefault = column.default !== null && column.default !== undefined;
	if (hasDefault && !column.identity && !column.generated)
		settings.push(`default: \`${column.default}\``);
	const note = column.generated ? `generated: ${column.default}` : notes.get(column.name);
	if (note) settings.push(`note: ${quoteText(note)}`);
	return `  ${column.name} ${typeName(column.type)}${settings.length > 0 ? ` [${settings.join(', ')}]` : ''}`;
}

function indexKey(key) {
	const text = key.column ?? key.expression;
	if (key.descending) return `\`${text} DESC\``;
	return key.column === null ? `\`${text}\`` : text;
}

function indexLine(index) {
	const keys = index.keys.map(indexKey);
	const target = keys.length === 1 ? keys[0] : `(${keys.join(', ')})`;
	const settings = [];
	if (index.primary) settings.push('pk');
	else {
		if (!index.constraint) settings.push(`name: ${quoteText(index.name)}`);
		if (index.unique) settings.push('unique');
	}
	if (index.where) settings.push(`note: ${quoteText(`where ${index.where}`)}`);
	return `    ${target}${settings.length > 0 ? ` [${settings.join(', ')}]` : ''}`;
}

function orderedIndexes(table) {
	return [...(table.indexes ?? [])].sort((a, b) => {
		const rank = (index) => (index.primary ? 0 : index.constraint ? 1 : 2);
		return rank(a) - rank(b) || byText(a.name, b.name);
	});
}

function renderTable(table) {
	const indexes = orderedIndexes(table);
	const primary = indexes.find((index) => index.primary);
	const singleKey =
		primary && primary.keys.length === 1 && !primary.where ? primary.keys[0].column : null;
	const notes = new Map();
	for (const check of table.checks ?? []) {
		const listed = listedValues(check);
		if (listed) notes.set(listed.column, listed.values.join(', '));
	}
	const lines = [`Table ${table.name} {`];
	for (const column of table.columns)
		lines.push(columnLine(column, column.name === singleKey, notes));
	const shown = indexes.filter(
		(index) => !(index.primary && index.keys[0].column === singleKey && singleKey)
	);
	if (shown.length > 0) {
		lines.push('', '  indexes {', ...shown.map(indexLine), '  }');
	}
	const extra = TABLE_NOTES[table.name];
	if (table.rls) lines.push(`  Note: ${quoteText(extra ? `RLS on. ${extra}` : 'RLS on')}`);
	lines.push('}');
	return lines.join('\n');
}

function side(table, columns) {
	return columns.length === 1 ? `${table}.${columns[0]}` : `${table}.(${columns.join(', ')})`;
}

function renderRef(ref) {
	const settings = [];
	if (ref.onDelete !== 'a') {
		const action = ACTIONS[ref.onDelete];
		settings.push(
			`delete: ${action}${ref.deleteColumns ? ` (${ref.deleteColumns.join(', ')})` : ''}`
		);
	}
	if (ref.onUpdate !== 'a') settings.push(`update: ${ACTIONS[ref.onUpdate]}`);
	return `Ref ${ref.name}: ${side(ref.table, ref.columns)} > ${side(ref.target, ref.targetColumns)}${settings.length > 0 ? ` [${settings.join(', ')}]` : ''}`;
}

function byText(a, b) {
	return a < b ? -1 : a > b ? 1 : 0;
}

export function renderDbml(catalog) {
	const tables = [...catalog.tables].sort((a, b) => byText(a.name, b.name));
	catalog.refs.sort((a, b) => byText(a.table, b.table) || byText(a.name, b.name));
	return `${HEADER}
Table auth.users {
  id uuid [pk]
  Note: 'Supabase Auth'
}

${tables.map(renderTable).join('\n\n')}

${catalog.refs.map(renderRef).join('\n')}
`;
}

function readCatalog(url) {
	const result = spawnSync('psql', [url, '-At', '-v', 'ON_ERROR_STOP=1', '-c', CATALOG_QUERY], {
		encoding: 'utf8',
		maxBuffer: 64 * 1024 * 1024
	});
	if (result.status !== 0) {
		throw new Error(`psql failed: ${result.stderr || result.error?.message}`);
	}
	return JSON.parse(result.stdout);
}

export function parseArgs(args, env = {}) {
	const urlIndex = args.indexOf('--url');
	const url = urlIndex >= 0 ? args[urlIndex + 1] : (env.DATABASE_URL ?? LOCAL_DATABASE);
	if (url === undefined || url.startsWith('--')) return null;
	return { url, check: args.includes('--check') };
}

function main(args) {
	if (args.includes('--help')) {
		console.log(USAGE);
		return 0;
	}
	const options = parseArgs(args, process.env);
	if (options === null) {
		console.error(`--url needs a value.\n${USAGE}`);
		return 2;
	}
	if (options.check && !existsSync(OUTPUT)) {
		console.error(
			'docs/data-model/current.dbml is missing. Run pnpm data-model and commit the result.'
		);
		return 1;
	}
	const dbml = renderDbml(readCatalog(options.url));
	if (options.check) {
		if (readFileSync(OUTPUT, 'utf8') === dbml) return 0;
		console.error(
			'docs/data-model/current.dbml is stale. Run pnpm data-model and commit the result.'
		);
		return 1;
	}
	writeFileSync(OUTPUT, dbml);
	console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
	return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	process.exitCode = main(process.argv.slice(2));
}
