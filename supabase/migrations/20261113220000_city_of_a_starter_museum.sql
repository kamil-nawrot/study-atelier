create function private.city_place_for(
  owner uuid,
  city_name text,
  city_wikidata_id text,
  city_country_code text,
  city_latitude double precision,
  city_longitude double precision
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  found uuid;
  found_type text;
begin
  if city_wikidata_id is not null then
    select details.value_id into found
      from public.location_details as details
      where details.owner_id = owner and details.wikidata_id = city_wikidata_id and details.place_type = 'city'
      order by details.value_id
      limit 1;
    if found is not null then
      return found;
    end if;
  end if;

  select value.id, details.place_type into found, found_type
    from public.category_values as value
    left join public.location_details as details on details.value_id = value.id
    where value.owner_id = owner and value.category_code = 'location' and lower(value.name) = lower(city_name);

  if found_type is not null and found_type <> 'city' then
    return null;
  end if;

  if found is null then
    insert into public.category_values (owner_id, category_code, name)
      values (owner, 'location', city_name)
      returning id into found;
  end if;

  insert into public.location_details as saved
      (value_id, owner_id, place_type, country_code, latitude, longitude, wikidata_id)
    values (found, owner, 'city', city_country_code, city_latitude, city_longitude, city_wikidata_id)
  on conflict (value_id) do update
    set place_type = 'city',
      city_id = null,
      country_code = coalesce(saved.country_code, excluded.country_code),
      latitude = case when saved.latitude is null then excluded.latitude else saved.latitude end,
      longitude = case when saved.latitude is null then excluded.longitude else saved.longitude end,
      wikidata_id = coalesce(saved.wikidata_id, excluded.wikidata_id);

  return found;
end;
$$;

revoke all on function private.city_place_for(uuid, text, text, text, double precision, double precision) from public;

create or replace function private.place_from_catalogue()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  museum public.catalogue_museums;
  city uuid;
begin
  if new.catalogue_wikidata_id is null or new.latitude is not null or new.city_id is not null then
    return new;
  end if;

  select * into museum from public.catalogue_museums as found
    where found.wikidata_id = new.catalogue_wikidata_id;
  if museum.wikidata_id is null then
    return new;
  end if;

  new.wikidata_id := coalesce(new.wikidata_id, museum.wikidata_id);

  if museum.city_name is not null
    and coalesce(current_setting('study_atelier.importing', true), '') <> 'on'
  then
    city := private.city_place_for(
      new.owner_id, museum.city_name, museum.city_wikidata_id, museum.city_country_code,
      museum.city_latitude, museum.city_longitude
    );
  end if;

  if city is not null then
    new.city_id := city;
  else
    new.latitude := museum.latitude;
    new.longitude := museum.longitude;
  end if;
  return new;
end;
$$;
