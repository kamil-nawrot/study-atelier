create table public.catalogue_museums (
  wikidata_id text primary key check (wikidata_id ~ '^Q[1-9][0-9]*$'),
  name text not null check (name <> '' and name = btrim(name)),
  english_name text check (english_name <> '' and english_name = btrim(english_name)),
  country_code text not null check (country_code ~ '^[A-Z]{2}$')
);

create unique index catalogue_museums_name_key on public.catalogue_museums (lower(name));

alter table public.catalogue_museums enable row level security;

create policy "Signed-in users read the museum catalogue"
  on public.catalogue_museums for select to authenticated
  using (true);

revoke all on public.catalogue_museums from anon, authenticated;
grant select on public.catalogue_museums to authenticated;

alter table public.location_details
  add column catalogue_wikidata_id text
    references public.catalogue_museums (wikidata_id) on delete set null;

grant insert (catalogue_wikidata_id) on public.location_details to authenticated;


