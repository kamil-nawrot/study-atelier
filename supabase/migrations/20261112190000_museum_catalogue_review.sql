update public.category_values as place
  set name = renamed.name
  from public.location_details as details
  join public.catalogue_museums as museum on museum.wikidata_id = details.catalogue_wikidata_id
  join museum_renames as renamed on renamed.wikidata_id = museum.wikidata_id
  where details.value_id = place.id
    and place.name = museum.name
    and not exists (
      select 1 from public.category_values as other
        where other.owner_id = place.owner_id
          and other.category_code = place.category_code
          and lower(other.name) = lower(renamed.name)
    );

update public.catalogue_museums as museum
  set name = renamed.name, alias = museum.name
  from museum_renames as renamed
  where renamed.wikidata_id = museum.wikidata_id;

